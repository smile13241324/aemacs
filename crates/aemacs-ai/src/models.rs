use std::fmt;

use serde::{Deserialize, Serialize};

/// Represents the role of a participant in a conversation.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum Role {
    /// The system prompt that sets the behavior and constraints of the model.
    #[serde(rename = "system")]
    System,
    /// The human user interacting with the model.
    #[serde(rename = "user")]
    User,
    /// The AI assistant generating responses.
    #[serde(rename = "assistant")]
    Assistant,
    /// A role representing the output of a tool execution.
    #[serde(rename = "tool")] // New Role for Tool Outputs
    Tool,
}

/// Represents the content of a message, which can be either a simple string
/// or a complex collection of content parts (e.g., text and images).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum Content {
    /// Simple text content.
    Text(String),
    /// A sequence of distinct content parts.
    Parts(Vec<ContentPart>),
}

impl From<String> for Content {
    fn from(s: String) -> Self {
        Self::Text(s)
    }
}

impl From<&str> for Content {
    fn from(s: &str) -> Self {
        Self::Text(s.to_string())
    }
}

impl fmt::Display for Content {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Text(s) => write!(f, "{s}"),
            Self::Parts(parts) => {
                for part in parts {
                    match part {
                        ContentPart::Text { text } => write!(f, "{text}")?,
                        ContentPart::ImageUrl { .. } => {},
                    }
                }
                Ok(())
            },
        }
    }
}

/// Represents a single part of a message's content.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ContentPart {
    /// A text segment.
    Text { text: String },
    /// An image reference.
    ImageUrl { image_url: ImageUrl },
}

/// Represents a URL for an image.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ImageUrl {
    /// The raw URL or data-URI of the image.
    pub url: String,
}

// --- Tooling ---

/// Represents a call to an external tool initiated by the AI model.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCall {
    /// A unique identifier for this specific tool call.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub id: Option<String>,
    /// The type of call (usually "function").
    #[serde(rename = "type")]
    pub call_type: String, // Usually "function"
    /// The specific function being invoked and its arguments.
    pub function: ToolCallFunction,
}

/// Represents the specific function details within a tool call.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolCallFunction {
    /// The name of the function to execute.
    pub name: String,
    /// The arguments for the function, provided as a JSON string.
    pub arguments: String, // JSON string
}

/// Represents a single message within a conversational exchange.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Message {
    /// The role of the message sender.
    pub role: Role,
    /// The primary content of the message.
    pub content: Content,
    /// Optional tool calls generated by the model during this message.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<ToolCall>>,

    /// For Tool Outputs: The ID of the tool call this message is responding to.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,

    /// The timestamp when the message was created.
    #[serde(default = "chrono::Utc::now")]
    pub timestamp: chrono::DateTime<chrono::Utc>,
}

impl Message {
    /// Creates a new message with the given role and content.
    pub fn new(role: Role, content: impl Into<Content>) -> Self {
        Self {
            role,
            content: content.into(),
            tool_calls: None,
            tool_call_id: None,
            timestamp: chrono::Utc::now(),
        }
    }

    /// Creates a new system message.
    pub fn system(content: impl Into<Content>) -> Self {
        Self::new(Role::System, content)
    }

    /// Creates a new user message.
    pub fn user(content: impl Into<Content>) -> Self {
        Self::new(Role::User, content)
    }

    /// Creates a new assistant message.
    pub fn assistant(content: impl Into<Content>) -> Self {
        Self::new(Role::Assistant, content)
    }

    /// Creates a new user message containing both text and an image.
    pub fn user_with_image(text: impl Into<String>, image_url: impl Into<String>) -> Self {
        let parts = vec![
            ContentPart::Text { text: text.into() },
            ContentPart::ImageUrl { image_url: ImageUrl { url: image_url.into() } },
        ];
        Self {
            role: Role::User,
            content: Content::Parts(parts),
            tool_calls: None,
            tool_call_id: None,
            timestamp: chrono::Utc::now(),
        }
    }
}

/// Specific configuration options for the Ollama inference engine.
#[derive(Debug, Clone, Serialize, Deserialize, Default)]
pub struct OllamaOptions {
    /// The size of the context window in tokens.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub num_ctx: Option<u32>,
    /// How long the model should remain in VRAM after the request.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub keep_alive: Option<String>,
}

/// Represents a request sent to an AI backend.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AIRequest {
    /// The name of the model to use.
    pub model: String,
    /// The conversation history leading up to this request.
    pub messages: Vec<Message>,
    /// The sampling temperature (creativity control).
    pub temperature: f32,
    /// Whether to stream the response as it is generated.
    pub stream: bool,
    /// Backend-specific options.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub options: Option<OllamaOptions>,
    /// Definitions of tools available for the model to call.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tools: Option<Vec<serde_json::Value>>, // Tool Definitions
}

impl Default for AIRequest {
    fn default() -> Self {
        Self {
            model: "default".to_string(),
            messages: Vec::new(),
            temperature: 0.7,
            stream: true,
            options: None,
            tools: None,
        }
    }
}

