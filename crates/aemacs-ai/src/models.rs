/// Defines the available hardware tiers for model selection.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModelTier {
    /// Optimized for laptops and low VRAM devices.
    Low,
    /// Optimized for high-end workstations.
    Medium,
    /// Optimized for server-grade multi-GPU systems.
    High,
}

/// Defines the specialized role of a model within the Bicameral pipeline.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModelRole {
    /// The executive hemisphere focused on technical analysis and tool use.
    Logic,
    /// A general-purpose creative model.
    Creative,
    /// The voice hemisphere focused on persona fidelity and prose synthesis.
    Roleplay,
}

/// Static definition of an AI model available in the registry.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ModelDefinition {
    /// The physical name of the model (for backend calls).
    pub name: &'static str,
    /// A human-readable label for the UI.
    pub label: &'static str,
    /// The hardware tier this model targets.
    pub tier: ModelTier,
    /// The specialized role of this model.
    pub role: ModelRole,
    /// Minimum VRAM required to load the weights.
    pub base_vram_gb: f32,
    /// Rate of VRAM consumption for the KV cache per 1000 tokens.
    pub kv_rate_gb_per_1k: f32,
    /// Absolute maximum context window supported by the model.
    pub max_context: u32,
    /// Plaintext description of license terms.
    pub license_constraints: &'static str,
    /// Detailed summary of the model's capabilities and training.
    pub model_description: &'static str,
    /// Whether this model supports function calling/tool use.
    pub supports_tools: bool,
}

